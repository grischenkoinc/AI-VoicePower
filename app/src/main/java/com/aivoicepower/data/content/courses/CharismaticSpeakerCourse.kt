Уяви двох спікерів на сцені. Перший: очі бігають по залу, голос невпевнений, постійно "е-е-е", читає зі слайдів, думки перестрибують. Другий: дивиться в очі людям, говорить спокійно і впевнено, паузи після важливих фраз, повністю тут. Хто тримає увагу? Другий. Це і є присутність.

Що таке присутність? Це стан повної зосередженості на моменті "тут і зараз". Ти не в минулому ("От, я помилився 2 хвилини тому"), не в майбутньому ("А що якщо зараз все зіпсую?"), не в голові ("Що мені сказати далі?"). Ти — ТУТ. З аудиторією. У цьому моменті.

Чому присутність настільки сильна? Тому що вона рідкісна. Більшість людей живуть у своїх думках, не у моменті. Коли хтось справді присутній — це виділяє його з натовпу. Це магніт для уваги.

Ознаки присутності у мовленні:
1. **Паузи без страху**: Ти не боїшся помовчати 2-3 секунди. Пауза = ти не поспішаєш, ти повністю контролюєш момент.
